function pairsOf(mine, theirs) {
  return PAIRS.map((axis, i) => axis[mine[i] + theirs[i]]);
}

function compatibility(mine, theirs) {
  return pairsOf(mine, theirs).reduce((sum, p) => sum + p.score, 0);
}

// 16유형 전체와 궁합 점수를 계산해서 가장 높은/낮은 유형을 고른다
function bestMatchOf(code) {
  return Object.keys(TYPES).reduce((a, b) => (compatibility(code, b) > compatibility(code, a) ? b : a));
}

function worstMatchOf(code) {
  return Object.keys(TYPES).reduce((a, b) => (compatibility(code, b) < compatibility(code, a) ? b : a));
}

// 두 유형의 조합에서 나온 이유 문장들 (best면 잘 맞는 것, worst면 부딪히는 것 위주)
function matchReasons(mine, theirs, kind) {
  const pairs = pairsOf(mine, theirs);
  const want = kind === "best" ? 1 : -1;
  return pairs.filter((p) => p.score === want).concat(pairs.filter((p) => p.score !== want)).map((p) => p.text);
}

